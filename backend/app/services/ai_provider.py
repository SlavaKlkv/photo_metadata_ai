from abc import ABC, abstractmethod
from pathlib import Path

from fastapi import HTTPException
from openai import AsyncOpenAI

from app.core.config import settings


class AIMetadataResponse:
    """
    Нормализованный ответ AI-провайдера с метаданными изображения.
    """

    def __init__(self, title: str, description: str, keywords: list[str]):
        self.title = title
        self.description = description
        self.keywords = keywords


class BaseAIProvider(ABC):
    """
    Базовый интерфейс AI-провайдера для анализа изображений.
    """

    @abstractmethod
    async def generate_metadata(self, image_path: Path) -> AIMetadataResponse:
        """
        Генерирует метаданные для изображения.
        """


class MockImageMetadataProvider(BaseAIProvider):
    """
    Тестовый AI-провайдер для локальной разработки без внешних API-запросов.
    """

    async def generate_metadata(self, image_path: Path) -> AIMetadataResponse:
        """
        Возвращает тестовые метаданные для изображения.
        """
        return AIMetadataResponse(
            title=f'Test metadata for {image_path.name}',
            description='Test image description generated by mock provider.',
            keywords=['test', 'image', 'metadata'],
        )


class OpenAIImageMetadataProvider(BaseAIProvider):
    """
    AI-провайдер на базе OpenAI для генерации metadata по изображению.
    """

    def __init__(self):
        if settings.OPENAI_API_KEY is None:
            raise HTTPException(
                status_code=500,
                detail='OPENAI_API_KEY is not configured',
            )

        self.client = AsyncOpenAI(api_key=settings.OPENAI_API_KEY)

    async def generate_metadata(self, image_path: Path) -> AIMetadataResponse:
        """
        Генерирует метаданные через OpenAI.
        """
        raise HTTPException(
            status_code=501,
            detail='OpenAI provider is not implemented yet',
        )


def get_ai_provider() -> BaseAIProvider:
    """
    Возвращает AI-провайдер по настройке DEFAULT_AI_PROVIDER.
    """
    if settings.DEFAULT_AI_PROVIDER == 'mock':
        return MockImageMetadataProvider()

    if settings.DEFAULT_AI_PROVIDER == 'openai':
        return OpenAIImageMetadataProvider()

    raise HTTPException(
        status_code=500,
        detail=f'Unsupported AI provider: {settings.DEFAULT_AI_PROVIDER}',
    )
